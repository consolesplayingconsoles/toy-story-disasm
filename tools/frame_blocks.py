#!/usr/bin/env python3
"""Split every identified sprite frame into its header and its tiles, for the rebuild's BLOCKS.

    frame_blocks.py <rom> log/toy_story_frame_blocks.py

A frame is a header ([w0 = 6 + 6*count][count][size in words] and its pieces: structured, it
counts only once written as source) followed by its tiles (a leaf asset: raw for objects,
run-length coded for Woody). Each frame is decoded here before its tiles are listed: Woody's
from his bank (all 400, by tools/frames.py's rules), Buzz's by walking each group in
GRAPHICS_USA['buzz_frames'] frame by frame. Writes addresses and names only, no game bytes.
"""
import os, struct, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'log'))
import toy_story_facts as f

d = open(sys.argv[1], 'rb').read()
g = f.GRAPHICS_USA
out = []

bank = g['sprite_frame']['player_bank']
for i in range(g['sprite_frame']['player_frames']):
    fr = bank + (struct.unpack_from('>I', d, bank + 4 * i)[0] & 0xFFFFFF)
    w0, count, size = struct.unpack_from('>HHH', d, fr)
    assert w0 == 6 + 6 * count
    cmd = fr + w0
    n = 0
    while d[cmd + n]:
        n += 1
    lit, p, made = cmd + 2 * ((n + 2) // 2), cmd, 0
    while d[p]:
        b = d[p]; p += 1
        if b & 0x80:
            made += 4 * (64 - ((b & 0x7F) >> 1))
        else:
            k = 65 - (b & 0x7F); made += 4 * k; lit += 4 * k
    assert made == size * 2, 'Woody frame %d decodes to %d, header says %d' % (i, made, size * 2)
    out.append((cmd, lit - 1, 'woody_frame_%03d_tiles' % i, 'rle_tiles'))


def frame_end(p):
    w0, count, size = struct.unpack_from('>HHH', d, p)
    if not (1 <= count <= 40 and w0 == 6 + 6 * count):
        return None
    pcs = [d[p + 6 + 6 * i:p + 12 + 6 * i] for i in range(count)]
    if sum((((q[0] >> 2) & 3) + 1) * ((q[0] & 3) + 1) for q in pcs) * 16 != size:
        return None
    return w0, p + w0 + size * 2


for name, v in g['buzz_frames'].items():
    if name == 'confidence':
        continue
    first, last, want = v
    p, k = first, 0
    while p <= last:
        fe = frame_end(p)
        assert fe, 'no Buzz frame at %X' % p
        w0, end = fe
        out.append((p + w0, end - 1, 'buzz_%s_%d_tiles' % (name, k), 'tiles'))
        k += 1
        p = end
    assert k == want, '%s: %d frames, expected %d' % (name, k, want)

out.sort()
with open(sys.argv[2], 'w') as w:
    w.write('# Generated by tools/frame_blocks.py: the tiles of every identified sprite frame, as rebuild\n'
            '# BLOCKS (start, end inclusive, name, format). Addresses and names only.\n'
            'FRAME_TILE_BLOCKS_USA = [\n')
    for s, e, n, fm in out:
        w.write('    (0x%06X, 0x%06X, %r, %r),\n' % (s, e, n, fm))
    w.write(']\n')
print('%d frames, %d bytes of tiles' % (len(out), sum(e - s + 1 for s, e, _, _ in out)))
